const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("mailCarrier", {
  getState: () => ipcRenderer.invoke("state:get"),
  saveSettings: (settings) => ipcRenderer.invoke("settings:save", settings),
  refreshProfiles: (settings, options) => ipcRenderer.invoke("profiles:refresh", settings, options),
  openProfiles: (envIds, options) => ipcRenderer.invoke("profiles:open", envIds, options),
  readGmail: (envIds, options) => ipcRenderer.invoke("profiles:read-gmail", envIds, options),
  hideProfiles: (envIds) => ipcRenderer.invoke("profiles:hide", envIds),
  restoreProfiles: (envIds) => ipcRenderer.invoke("profiles:restore", envIds),
  importContacts: () => ipcRenderer.invoke("contacts:import"),
  importTemplates: (kind) => ipcRenderer.invoke("templates:import", kind),
  downloadTemplateSamples: (group) => ipcRenderer.invoke("templates:sample", group),
  importAccountContacts: (payload) => ipcRenderer.invoke("contacts:import-account", payload),
  clearAccountContacts: (payload) => ipcRenderer.invoke("contacts:clear-account", payload),
  clearContacts: () => ipcRenderer.invoke("contacts:clear"),
  pickCv: () => ipcRenderer.invoke("cv:pick"),
  savePrefs: (prefs) => ipcRenderer.invoke("prefs:save", prefs),
  startCampaign: (payload) => ipcRenderer.invoke("campaign:start", payload),
  stopCampaign: (payload) => ipcRenderer.invoke("campaign:stop", payload || {}),
  pauseCampaign: (payload) => ipcRenderer.invoke("campaign:pause", payload || {}),
  resumeCampaign: (payload) => ipcRenderer.invoke("campaign:resume", payload || {}),
  setBetweenAccounts: (payload) => ipcRenderer.invoke("campaign:between-accounts", payload || {}),
  setJobInterval: (payload) => ipcRenderer.invoke("campaign:interval", payload || {}),
  saveWarmup: (warmup) => ipcRenderer.invoke("warmup:save", warmup),
  saveGmailStatus: (payload) => ipcRenderer.invoke("gmail-status:save", payload),
  startWarmup: (payload) => ipcRenderer.invoke("warmup:start", payload),
  startPeerWarmup: (payload) => ipcRenderer.invoke("warmup:start-peers", payload),
  applyWarmupPlan: (payload) => ipcRenderer.invoke("warmup:apply-plan", payload),
  runWarmupPlan: (payload) => ipcRenderer.invoke("warmup:run-plan", payload),
  saveFollowup: (followup) => ipcRenderer.invoke("followup:save", followup),
  startFollowup: (payload) => ipcRenderer.invoke("followup:start", payload),
  startDueFollowups: (payload) => ipcRenderer.invoke("followup:start-due", payload),
  saveAnalysis: (payload) => ipcRenderer.invoke("analyse:save", payload),
  startAnalysis: (payload) => ipcRenderer.invoke("analyse:start", payload),
  clearGmailConnections: () => ipcRenderer.invoke("connections:clear"),
  onEvent: (callback) => {
    ipcRenderer.on("app:event", (_event, data) => callback(data));
  },
});
